/** Authoring tool: synthesize the reviewed story scripts once, then ship offline MP3s. */
import fs from 'node:fs/promises'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { createServer } from 'vite'
import { ProxyAgent, Socks5ProxyAgent, setGlobalDispatcher } from 'undici'
const proxy = process.env.SPEECH_PROXY_URL || process.env.HTTPS_PROXY || process.env.ALL_PROXY
if (proxy)
  setGlobalDispatcher(
    proxy.startsWith('socks') ? new Socks5ProxyAgent(proxy) : new ProxyAgent(proxy)
  )
const server = await createServer({
  configFile: false,
  root: process.cwd(),
  logLevel: 'error',
  optimizeDeps: { noDiscovery: true, include: [] },
  server: { middlewareMode: true, hmr: false, watch: null },
  resolve: { alias: { '@shared': path.resolve('src/shared') } }
})
const output = path.resolve('src/renderer/src/features/long-march/assets/stories')
const cache = path.resolve('.codegen/march-story-audio')
const voice = 'zh-CN-YunjianNeural'
const probe = (file) => {
  const result = spawnSync(
    'ffprobe',
    ['-v', 'error', '-show_entries', 'format=duration', '-of', 'json', file],
    { encoding: 'utf8' }
  )
  if (result.status !== 0) throw new Error(result.stderr)
  return Number(JSON.parse(result.stdout).format.duration)
}
try {
  const { MARCH_STORIES } = await server.ssrLoadModule('/src/shared/long-march-stories.ts')
  const { synthesizeEdge } = await server.ssrLoadModule('/src/main/adapters/speech/edge.ts')
  await fs.mkdir(output, { recursive: true })
  await fs.mkdir(cache, { recursive: true })
  let cursor = 0
  const timing = {}
  async function worker() {
    while (cursor < MARCH_STORIES.length) {
      const story = MARCH_STORIES[cursor++]
      const parts = [],
        starts = []
      let elapsed = 0
      for (const section of story.sections) {
        const text = `${section.title}。${section.text}`
        const key = createHash('sha256').update(JSON.stringify({ voice, text })).digest('hex')
        const file = path.join(cache, `${key}.mp3`)
        try {
          await fs.access(file)
          probe(file)
        } catch {
          let audio
          for (let attempt = 0; attempt < 8; attempt++) {
            try {
              audio = await synthesizeEdge({ id: key, text, voice }, AbortSignal.timeout(60000))
              break
            } catch (error) {
              if (attempt === 7) throw error
              console.log(`Retry ${story.id}/${section.title}: ${error.message}`)
              await new Promise((resolve) =>
                setTimeout(resolve, Math.min(2000 * 2 ** attempt, 12000))
              )
            }
          }
          await fs.writeFile(file, audio)
        }
        starts.push(+elapsed.toFixed(3))
        elapsed += probe(file)
        parts.push(file)
      }
      const list = path.join(cache, `${story.id}.concat`)
      await fs.writeFile(
        list,
        parts.map((file) => `file '${file.replace(/'/g, "'\\''")}'`).join('\n')
      )
      const destination = path.join(output, `${story.id}.mp3`)
      const merged = spawnSync(
        'ffmpeg',
        ['-v', 'error', '-y', '-f', 'concat', '-safe', '0', '-i', list, '-c', 'copy', destination],
        { encoding: 'utf8' }
      )
      if (merged.status !== 0) throw new Error(merged.stderr)
      const decoded = spawnSync('ffmpeg', ['-v', 'error', '-i', destination, '-f', 'null', '-'], {
        encoding: 'utf8'
      })
      if (decoded.status !== 0 || decoded.stderr.trim()) throw new Error(decoded.stderr)
      timing[story.id] = {
        duration: probe(destination),
        starts,
        voice,
        scriptHash: createHash('sha256').update(JSON.stringify(story.sections)).digest('hex')
      }
      console.log(`Verified ${story.id}: ${timing[story.id].duration.toFixed(1)}s`)
    }
  }
  await worker()
  const ordered = Object.fromEntries(MARCH_STORIES.map((story) => [story.id, timing[story.id]]))
  await fs.writeFile(
    path.resolve('src/renderer/src/features/long-march/story-audio-timing.ts'),
    `// Generated by scripts/generate-march-story-audio.mjs; actual audio boundaries.\nexport const storyAudioTiming: Record<string, {duration:number; starts:number[]; voice:string; scriptHash:string}> = ${JSON.stringify(ordered, null, 2)}\n`
  )
  console.log('All 12 offline story narrations ready.')
} finally {
  await server.close()
}
